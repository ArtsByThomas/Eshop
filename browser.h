const char* strstr(const char* haystack, const char* needle) {
    if (!*needle) return haystack; 
    for (; *haystack; ++haystack) {
        const char *h = haystack;
        const char *n = needle;
        while (*h && *n && *h == *n) { ++h; ++n; }
        if (!*n) return haystack;
    }
    return 0; 
}
