void draw_glyph_by_index_scaled(int x, int y, int index, uint32_t color, int scale) {
    for (int row = 0; row < 8; row++) {
        uint8_t line = font8x8[index][row];
        if (line == 0) continue; 
        for (int sy = 0; sy < scale; sy++) {
            int py = y + row * scale + sy - scroll_y;
            if (py < 0 || py >= browser_height) continue;
            uint32_t* row_ptr = &pixel_buffer[py * browser_width];
            for (int col = 0; col < 8; col++) {
                if (line & (0x80 >> col)) {
                    int base_px = x + col * scale;
                    for (int sx = 0; sx < scale; sx++) {
                        int px = base_px + sx;
                        if (px >= 0 && px < browser_width) row_ptr[px] = color;
                    }
                }
            }
        }
    }
}

