void draw_rounded_rect_user(int x, int y, int w, int h, int r, uint32_t color) {
    if (r <= 0) { 
        draw_rect_user(x, y, w, h, color); 
        return; 
    }
    
    if (r > w / 2) r = w / 2;
    if (r > h / 2) r = h / 2;

    int y0 = y - scroll_y;
    int y1 = y0 + h;

    for (int py = y0; py < y1; py++) {
        if (py < 0 || py >= browser_height) continue;

        int dy = 0;
        if (py < y0 + r) dy = (y0 + r) - py;
        else if (py > y1 - 1 - r) dy = py - (y1 - 1 - r);

        int start_x = x;
        int end_x = x + w;

        if (dy > 0) {
 
            int dx = r;
            while (dx * dx + dy * dy > r * r && dx > 0) {
                dx--;
            }
            int indent = r - dx;
            start_x += indent;
            end_x -= indent;
        }
        
        fill_row_fast(py, start_x, end_x, color);
    }
}
